"""Supplementary statistics for the final report, written as LaTeX macros (\\finx...).

final_analyze.py stays the source of the headline tables. This script reuses its loaders and its block test
(compare: per-block metric, Wilcoxon signed-rank, super-block bootstrap) and adds what the report also needs:

  * additional test-block subsets for robustness checks, including the blocks held back for the final evaluation
    (the smoke/quick-run blocks are excluded)
  * block tests per lead, coverage / below-P10 by lead and season, pooled relative differences
  * per-seed RMSE, bias, below-P10 and full tests vs gbm_base; seed ranges of coverage and below-P10
  * error by green-last tercile (unit share of pixels whose last clear input was green, NDVI >= 0.30)
  * training configuration, the discarded Earthformer lr 1e-3 run, GBM/ridge selection, extra counts

Usage: python final_extra.py [--dir results_v2/final]   (writes final_numbers_extra.tex and extra.json there)
"""
import argparse
import json
import os

import numpy as np
import pandas as pd

import final_analyze as FA

UNIT = FA.UNIT
PAIRS = [("gbm_base", "persistence", "GbmVsPers"), ("gbm_base", "climatology", "GbmVsClim"),
         ("convlstm", "gbm_base", "ConvLSTMVsGbm"), ("earthformer", "gbm_base", "EarthformerVsGbm"),
         ("earthformer", "convlstm", "EarthformerVsConvLSTM"), ("convlstm", "persistence", "ConvLSTMVsPers"),
         ("earthformer", "persistence", "EarthformerVsPers")]
SMOKE_DIRS = ["final_quick", os.path.join("final", "smoke"), os.path.join("final", "smoke_review"),
              os.path.join("final", "smoke_review_es")]
# test blocks scored by smoke/quick runs before the final evaluation (read from SMOKE_DIRS when present)
SMOKE_FALLBACK = [211, 244, 245, 246]
KEYM = {"persistence": "Pers", "climatology": "Clim", "gbm_base": "Gbm", "convlstm": "ConvLSTM",
        "earthformer": "Earthformer", "ridge": "Ridge", "seasonal": "Seas"}
LW = {1: "One", 2: "Two", 3: "Three"}


def load(d):
    df = pd.read_csv(os.path.join(d, "rows.csv"))
    df = df[df.split == "test"]
    models = [m for m in FA.ORDER if m in set(df.model)]
    core_models = [m for m in models if not m.startswith("gbm_") or m == "gbm_base"]
    core = FA.common(df, core_models)
    nn, runs, use, skipped = FA.load_neural(d, core)
    assert nn is not None and not skipped, "needs complete neural runs"
    dfa = pd.concat([df, nn], ignore_index=True)
    FA.check_pixels(dfa)
    dfa = pd.concat([dfa] + [FA.seed_mean(nn, m, use[m]) for m in FA.NEURAL], ignore_index=True)
    sbmap = df.groupby("block").superblock.first().to_dict()
    return df, dfa, runs, use, sbmap


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(FA.ROOT, "results_v2", "final"))
    a = ap.parse_args()
    res_root = os.path.dirname(os.path.abspath(a.dir))
    df, dfa, runs, use, sbmap = load(a.dir)
    X, L = {}, ["% generated by final_extra.py from results_v2/final -- do not edit"]
    c = lambda name, val: L.append(r"\newcommand{\finx%s}{%s}" % (name, val))
    num, pval = FA.num, FA.pval
    pct = lambda v, d=1: "--" if v is None or not np.isfinite(v) else f"{100 * v:.{d}f}"

    def put_test(prefix, t, d=5):
        for met, mk in (("mae", ""), ("pinball", "Pin")):
            v = t[met]
            c(f"{prefix}{mk}Wins", v["wins"]); c(f"{prefix}{mk}Blocks", v["blocks"])
            c(f"{prefix}{mk}Diff", num(v["mean_diff"], d)); c(f"{prefix}{mk}Lo", num(v["ci95"][0], d))
            c(f"{prefix}{mk}Hi", num(v["ci95"][1], d)); c(f"{prefix}{mk}P", pval(v["wilcoxon_p"]))
            c(f"{prefix}{mk}Rel", pct(v["rel_diff"]))

    # ---------------------------------------------------------------- A. additional test subsets
    plan = json.load(open(os.path.join(res_root, "ndti_local", "plan.json")))
    test_blocks = sorted(int(b) for b in df.block.unique())
    week9 = sorted(int(b) for b in plan["fast_test"])
    smoke = set()
    for sd in SMOKE_DIRS:
        for fn in ("rows.csv", "neural_rows.csv"):
            p = os.path.join(res_root, sd, fn)
            if os.path.exists(p):
                s = pd.read_csv(p, usecols=lambda col: col in ("block", "split"))
                if "split" in s:
                    s = s[s.split == "test"]
                smoke |= set(int(b) for b in s.block.unique()) & set(test_blocks)
    found = any(os.path.exists(os.path.join(res_root, sd)) for sd in SMOKE_DIRS)
    if not found:   # the smoke/quick-run folders are not shipped with the code; use the list they produced
        smoke = set(SMOKE_FALLBACK)
    else:
        assert smoke == set(SMOKE_FALLBACK), (sorted(smoke), SMOKE_FALLBACK)
    subsets = {"NotWkNine": [b for b in test_blocks if b not in week9],
               "Untouched": [b for b in test_blocks if b not in week9 and b not in smoke]}
    X["exposure"] = {"week9_blocks": week9, "smoke_blocks": sorted(smoke),
                     "subsets": subsets, "all_test_blocks": test_blocks}
    c("NWeekNineBlocks", len(week9)); c("NSmokeBlocks", len(smoke - set(week9)))
    for sk, blocks in subsets.items():
        sub = dfa[dfa.block.isin(blocks)]
        c(f"{sk}NBlocks", len(blocks)); c(f"{sk}NSuperblocks", len({sbmap[b] for b in blocks}))
        c(f"{sk}NPixel", f"{int(sub[sub.model == 'persistence'].n.sum()):,}")
        X.setdefault("subset_tests", {})[sk] = {}
        for m in ("persistence", "climatology", "gbm_base", "convlstm", "earthformer"):
            g = sub[sub.model == m]
            mm = FA.metrics(g, m)
            c(f"{sk}{KEYM[m]}MAE", num(mm["mae"])); c(f"{sk}{KEYM[m]}Pin", num(mm["pinball"]))
        for a_, b_, nm in PAIRS:
            t = FA.compare(sub, a_, b_, sbmap)
            X["subset_tests"][sk][nm] = t
            put_test(f"{sk}{nm}", t)

    # ---------------------------------------------------------------- B. per-lead tests, calibration by lead/season
    X["lead_tests"] = {}
    for lead in (1, 2, 3):
        sub = dfa[dfa.lead == lead]
        X["lead_tests"][lead] = {}
        for a_, b_, nm in PAIRS:
            t = FA.compare(sub, a_, b_, sbmap)
            X["lead_tests"][lead][nm] = t
            put_test(f"Lead{LW[lead]}{nm}", t)
    for by, keyf in (("lead", lambda v: "Lead" + LW[int(v)]), ("season", lambda v: FA.yearword(v))):
        for m in ("climatology", "gbm_base", "convlstm", "earthformer"):
            for v, g in dfa[dfa.model == m].groupby(by):
                mm = FA.metrics(g, m)
                c(f"Cov{keyf(v)}{KEYM[m]}", num(mm["cover80"], 3)); c(f"Below{keyf(v)}{KEYM[m]}", num(mm["below10"], 3))

    # ---------------------------------------------------------------- C. pooled relative differences
    pooled = {m: FA.metrics(dfa[dfa.model == m], m) for m in ("persistence", "climatology", "gbm_base",
                                                              "convlstm", "earthformer")}
    X["pooled"] = pooled
    for a_, b_, nm in PAIRS:
        for met, mk in (("mae", "MAE"), ("pinball", "Pin")):
            c(f"Pooled{nm}{mk}Rel", pct(pooled[a_][met] / pooled[b_][met] - 1, 1))
    for m in ("gbm_base", "convlstm", "earthformer", "climatology"):
        c(f"{KEYM[m]}MAEFive", num(pooled[m]["mae"], 5)); c(f"{KEYM[m]}PinFive", num(pooled[m]["pinball"], 5))
        c(f"{KEYM[m]}RelMAEVsClim", pct(1 - pooled[m]["mae"] / pooled["climatology"]["mae"], 1))
        c(f"{KEYM[m]}RelMAEVsPers", pct(1 - pooled[m]["mae"] / pooled["persistence"]["mae"], 1))

    # ---------------------------------------------------------------- D. per-seed details
    X["seeds"] = {}
    for arch in FA.NEURAL:
        A = {"convlstm": "ConvLSTM", "earthformer": "Earthformer"}[arch]
        covs, belows = [], []
        for s in sorted(use[arch]):
            run = f"{arch}_s{s}"
            mm = FA.metrics(dfa[dfa.model == run], run)
            W = FA.SEEDWORD[s]
            c(f"{A}{W}RMSE", num(mm["rmse"])); c(f"{A}{W}Bias", num(mm["bias"], 5))
            c(f"{A}{W}Below", num(mm["below10"], 3)); c(f"{A}{W}Cov", num(mm["cover80"], 3))
            c(f"{A}{W}MAEFive", num(mm["mae"], 5)); c(f"{A}{W}PinFive", num(mm["pinball"], 5))
            covs.append(mm["cover80"]); belows.append(mm["below10"])
            t = FA.compare(dfa, run, "gbm_base", sbmap)
            put_test(f"{A}{W}VsGbm", t)
            info = runs[run]
            c(f"{A}{W}BestVal", num(info["best_val_pinball"], 5))
            resumed = info.get("timing_note") and info.get("resumed_after_epoch") is not None
            c(f"{A}{W}PeakGpuTrain", "n/a" if resumed else f"{info['peak_gpu_gb']:.2f}")
            X["seeds"][run] = {"metrics": mm, "vs_gbm": t, "resumed_after_epoch": info.get("resumed_after_epoch")}
        c(f"{A}CovMin", num(min(covs), 3)); c(f"{A}CovMax", num(max(covs), 3))
        c(f"{A}BelowMin", num(min(belows), 3)); c(f"{A}BelowMax", num(max(belows), 3))
        ok = [runs[f"{arch}_s{s}"]["peak_gpu_gb"] for s in use[arch]
              if runs[f"{arch}_s{s}"].get("resumed_after_epoch") is None]
        c(f"{A}PeakGpuMin", f"{min(ok):.2f}"); c(f"{A}PeakGpuMax", f"{max(ok):.2f}")
        mm = FA.metrics(dfa[dfa.model == arch], arch)
        c(f"{A}AggRMSE", num(mm["rmse"])); c(f"{A}AggBias", num(mm["bias"], 5)); c(f"{A}AggBelow", num(mm["below10"], 3))
        h = runs[f"{arch}_s{use[arch][0]}"]["hyper"]
        c(f"{A}LR", f"{h['lr']:g}"); c(f"{A}WD", f"{h['wd']:g}"); c(f"{A}Warmup", f"{100 * h['warmup']:.0f}")
        c(f"{A}BS", h["bs"]); c(f"{A}Patience", h["patience"])
        tm = sum(runs[f"{arch}_s{s}"]["train_minutes"] for s in use[arch])
        c(f"{A}TrainHours", f"{tm / 60:.1f}")
    r0 = runs[f"convlstm_s{use['convlstm'][0]}"]
    c("EpochBudget", r0["epoch_budget"]); c("NTrainSamples", f"{r0['n_train_samples']:,}")
    c("NValSamples", f"{r0['n_val_samples']:,}"); c("StepsPerEpoch", f"{r0['steps_per_epoch']:,}")
    c("TilesPerWindow", r0.get("tiles_per_window", 25)); c("Patch", r0.get("patch", 128))
    gpu_total = sum(v["train_minutes"] for k, v in runs.items() if k.split("_s")[0] in FA.NEURAL)
    c("NeuralTrainHours", f"{gpu_total / 60:.1f}")
    c("GPU", (r0.get("gpu") or "").replace("NVIDIA GeForce ", ""))
    c("EFCommit", (runs[f"earthformer_s{use['earthformer'][0]}"].get("earthformer_commit") or "")[:7])

    # discarded Earthformer configuration (archived, not part of any result)
    arc = os.path.join(a.dir, "archive_earthformer_lr1e-3", "earthformer_s340_run.json")
    if os.path.exists(arc):
        r = json.load(open(arc))
        r = r.get("earthformer_s340", r)
        hist = r["history"]
        vals = [h_["val"] for h_ in hist]
        c("DivLR", f"{r['hyper']['lr']:g}"); c("DivWarmup", f"{100 * r['hyper']['warmup']:.0f}")
        c("DivBestEpoch", r["best_epoch"]); c("DivEpochsRun", r["epochs_run"])
        c("DivBestVal", num(min(vals), 4)); c("DivValAfter", num(vals[r["best_epoch"]], 4))
        c("DivTrainAtBest", num(hist[r["best_epoch"] - 1]["train"], 4)); c("DivTrainAfter", num(hist[r["best_epoch"]]["train"], 4))
        ts = r["test_summary"]
        c("DivTestMAE", num(ts["mae"], 4)); c("DivTestPin", num(ts["pinball"], 5))
        X["discarded_earthformer"] = {k: r[k] for k in ("hyper", "best_epoch", "epochs_run", "test_summary")}

    # ---------------------------------------------------------------- E. green-last terciles
    p = dfa[dfa.model == "persistence"].copy()
    p["gshare"] = p.lastgreen / p.n
    cuts = np.quantile(p.gshare.values, [1 / 3, 2 / 3])
    p["gterc"] = np.digitize(p.gshare, cuts)
    gmap = p[UNIT + ["gterc"]]
    c("GreenLastShare", pct(p.lastgreen.sum() / p.n.sum(), 0))
    c("GreenCutLo", pct(cuts[0], 0)); c("GreenCutHi", pct(cuts[1], 0))
    X["green_terciles"] = {"cuts": cuts.tolist()}
    for m in ("persistence", "climatology", "gbm_base", "convlstm", "earthformer"):
        g = dfa[dfa.model == m].merge(gmap, on=UNIT, how="inner")
        for k, gg in g.groupby("gterc"):
            mm = FA.metrics(gg, m)
            c(f"{KEYM[m]}MAEGreen{LW[k + 1]}", num(mm["mae"]))
            X["green_terciles"].setdefault(m, {})[int(k)] = mm
    for k in range(3):
        sh = p[p["gterc"] == k]
        c(f"GreenTercileShare{LW[k + 1]}", pct(sh.lastgreen.sum() / sh.n.sum(), 0))
        gain_p = X["green_terciles"]["persistence"][k]["mae"] - X["green_terciles"]["gbm_base"][k]["mae"]
        c(f"GbmGainGreen{LW[k + 1]}", pct(gain_p / X["green_terciles"]["persistence"][k]["mae"], 0))

    # ---------------------------------------------------------------- F. CPU selection and counts
    fit = json.load(open(os.path.join(a.dir, "fit.json")))
    st = fit["settings"]
    c("GbmLRGrid", ", ".join(f"{v:g}" for v in st["lrs"])); c("GbmCap", st["cap"]); c("GbmLeaves", st["leaf"])
    c("GbmMinLeaf", st["minleaf"]); c("PerUnitPx", st["per"]); c("ClimMinYears", st["clim_min_years"])
    fb = fit["fallback_share"]
    for m, k in (("climatology", "Clim"), ("persistence_ng", "PersNG"), ("seasonal", "Seas")):
        c(f"Fallback{k}", pct(fb[m], 1))
    c("NTrainBlockSeasons", len(fit["train_block_seasons"])); c("NValBlockSeasons", len(fit["val_block_seasons"]))
    c("NTestBlockSeasons", len(fit["test_block_seasons"]))
    c("NTrainBlocks", len({b for b, _ in fit["train_block_seasons"]})); c("NValBlocks", len({b for b, _ in fit["val_block_seasons"]}))
    pers = dfa[dfa.model == "persistence"]
    c("NUnitsPossible", len(test_blocks) * 2 * 6 * 3); c("NUnitsEmpty", len(test_blocks) * 2 * 6 * 3 - pers.groupby(UNIT).ngroups)
    for lead in (1, 2, 3):
        c(f"NPixelLead{LW[lead]}", f"{pers[pers.lead == lead].n.sum() / 1e6:.1f}")
    seas = dfa[dfa.model == "seasonal"]
    for y, g in seas.groupby("season"):
        c(f"FallbackSeas{FA.yearword(y)}", pct(g.nfb.sum() / g.n.sum(), 1))

    out = os.path.join(a.dir, "final_numbers_extra.tex")
    names = [l.split("}")[0] for l in L[1:]]
    assert len(names) == len(set(names)), [n for n in names if names.count(n) > 1][:5]
    with open(out + ".tmp", "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    os.replace(out + ".tmp", out)
    json.dump(X, open(os.path.join(a.dir, "extra.json"), "w"), indent=1, default=float)
    print(f"wrote {out} ({len(L) - 1} macros) and extra.json")
    for sk in subsets:
        for nm in ("GbmVsPers", "GbmVsClim", "ConvLSTMVsGbm", "EarthformerVsGbm", "EarthformerVsConvLSTM"):
            t = X["subset_tests"][sk][nm]["mae"]
            print(f"{sk:10s} {nm:22s} wins {t['wins']}/{t['blocks']} diff {t['mean_diff']:+.5f} "
                  f"CI [{t['ci95'][0]:+.5f},{t['ci95'][1]:+.5f}] p={t['wilcoxon_p']:.4f}")
    for lead in (1, 2, 3):
        for nm in ("ConvLSTMVsGbm", "EarthformerVsGbm", "GbmVsPers"):
            t = X["lead_tests"][lead][nm]["mae"]
            print(f"lead {lead} {nm:20s} wins {t['wins']}/{t['blocks']} diff {t['mean_diff']:+.5f} "
                  f"CI [{t['ci95'][0]:+.5f},{t['ci95'][1]:+.5f}] p={t['wilcoxon_p']:.4f}")


if __name__ == "__main__":
    main()
