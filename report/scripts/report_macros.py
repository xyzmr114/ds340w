"""Report-side LaTeX macros (\\finy...) that final_analyze.py and final_extra.py do not write.

Everything here is recomputed from the project's result files with the project's own loaders and block test
(pipelines/final_analyze.py, pipelines/final_extra.py), which are imported read-only (no bytecode is written):

  * number formats the report needs: 1,152 possible units, learning rates and weight decay in scientific
    notation, coverage and below-P10 at three decimals for every quantile model
  * ConvLSTM / Earthformer vs GBM block tests (all leads pooled) with five-decimal differences and intervals
  * per-division block counts, green-last pixel share, mean clear-observation rate and pooled GBM gain
  * block ranges of the green-last share and of the clear rate as percentages
  * the share of the pooled absolute-error reduction (persistence minus GBM) that comes from pixels whose
    last clear input was green, from green_gain.json (written by green_gain.py at pixel level)

Usage: python -B report_macros.py   -> ../final_numbers_report.tex
"""
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("DS340W_ROOT", os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")))
PIPE = os.path.join(ROOT, "pipelines")
sys.path.insert(0, PIPE)
import numpy as np  # noqa: E402
import final_analyze as FA  # noqa: E402
import final_extra as FX  # noqa: E402

R = os.path.join(FA.ROOT, "results_v2", "final")


def sci(v):
    """LaTeX scientific notation: 0.001 -> $10^{-3}$, 0.00025 -> $2.5\\times10^{-4}$."""
    m, e = f"{v:e}".split("e")
    m = float(m)
    e = int(e)
    ms = f"{m:g}"
    return f"$10^{{{e}}}$" if ms == "1" else f"${ms}\\times10^{{{e}}}$"


def main():
    L = ["% generated by output/final/scripts/report_macros.py -- do not edit"]
    c = lambda name, val: L.append(r"\newcommand{\finy%s}{%s}" % (name, val))
    num, pval = FA.num, FA.pval
    pct = lambda v, d=0: f"{100 * v:.{d}f}"

    df, dfa, runs, use, sbmap = FX.load(R)
    S = json.load(open(os.path.join(R, "summary.json")))

    # ---- formats
    test_blocks = sorted(int(b) for b in df.block.unique())
    c("NUnitsPossible", f"{len(test_blocks) * 2 * 6 * 3:,}".replace(",", "{,}"))
    for arch, A in (("convlstm", "ConvLSTM"), ("earthformer", "Earthformer")):
        h = runs[f"{arch}_s{use[arch][0]}"]["hyper"]
        c(f"{A}LR", sci(h["lr"])); c(f"{A}WD", sci(h["wd"]))
    arc = os.path.join(R, "archive_earthformer_lr1e-3", "earthformer_s340_run.json")
    r = json.load(open(arc)); r = r.get("earthformer_s340", r)
    c("DivLR", sci(r["hyper"]["lr"]))
    for m in ("climatology", "gbm_base", "gbm_rain", "gbm_soil", "gbm_temp", "gbm_chirps", "gbm_all",
              "convlstm", "earthformer"):
        mm = FA.metrics(dfa[dfa.model == m], m)
        k = FA.KEY[m]
        c(f"{k}Cov", num(mm["cover80"], 3)); c(f"{k}Below", num(mm["below10"], 3))

    # ---- five-decimal neural vs GBM tests (all leads); wins and p must equal final_numbers.tex
    for a_, nm in (("convlstm", "ConvLSTMVsGbm"), ("earthformer", "EarthformerVsGbm")):
        t = FA.compare(dfa, a_, "gbm_base", sbmap)["mae"]
        ref = S["tests"][f"{a_}_vs_gbm_base"]["mae"]
        assert t["wins"] == ref["wins"] and abs(t["wilcoxon_p"] - ref["wilcoxon_p"]) < 1e-12, nm
        c(f"{nm}Diff", num(t["mean_diff"], 5)); c(f"{nm}Lo", num(t["ci95"][0], 5)); c(f"{nm}Hi", num(t["ci95"][1], 5))

    # ---- divisions
    pers = dfa[dfa.model == "persistence"]
    blk = S["blocks"]
    for reg, g in pers.groupby("region"):
        bl = [b for b, v in blk.items() if v["region"] == reg]
        c(f"NBlocks{reg}", len(bl))
        c(f"GreenShare{reg}", pct(g.lastgreen.sum() / g.n.sum()))
        c(f"ClearRate{reg}", pct(np.mean([blk[b]["clear_rate"] for b in bl])))
        pm = S["by_region"]["persistence"][reg]["mae"]; gm = S["by_region"]["gbm_base"][reg]["mae"]
        cm = S["by_region"]["climatology"][reg]["mae"]
        c(f"GbmGain{reg}", pct(1 - gm / pm))
        c(f"PersOverClim{reg}", f"{pm / cm:.1f}")
    rng = S["covariate_ranges"]
    c("RangeGreenLo", pct(rng["green_last_share"][0])); c("RangeGreenHi", pct(rng["green_last_share"][1]))
    c("RangeClearLo", pct(rng["clear_rate"][0])); c("RangeClearHi", pct(rng["clear_rate"][1]))

    # ---- pixel-level green-last share of the pooled gain against persistence
    gp = os.path.join(HERE, "green_gain.json")
    if os.path.exists(gp):
        G = json.load(open(gp))
        pm = S["pooled"]["persistence"]["mae"]; gm = S["pooled"]["gbm_base"]["mae"]
        assert G["n"] == int(pers.n.sum()), (G["n"], int(pers.n.sum()))
        assert abs(G["pers_mae"] - pm) < 1e-7 and abs(G["gbm_mae"] - gm) < 1e-6, (G["pers_mae"], pm, G["gbm_mae"], gm)
        c("GreenGainShare", pct(G["green_share_of_gain_vs_pers"]))
        c("GreenPixelShare", pct(G["green_pixel_share"]))
    else:
        print("note: green_gain.json missing; run green_gain.py first")

    out = os.path.join(os.path.dirname(HERE), "final_numbers_report.tex")
    names = [l.split("}")[0] for l in L[1:]]
    assert len(names) == len(set(names))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
